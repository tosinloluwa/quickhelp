-- Run ONLY in the existing QuickHelp portal database, not QuickCommerce/Qknows.
CREATE TABLE IF NOT EXISTS qha_phone_verifications (
 user_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 phone VARCHAR(20) NOT NULL UNIQUE,
 verified_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS qha_google_accounts (
 subject VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS qha_oauth_flows (
 id CHAR(64) CHARACTER SET ascii NOT NULL PRIMARY KEY,
 state_hash CHAR(64) CHARACTER SET ascii NOT NULL UNIQUE,
 verifier VARCHAR(128) NOT NULL,
 nonce VARCHAR(128) NOT NULL,
 user_id BIGINT UNSIGNED NULL,
 referrer VARCHAR(191) NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 error VARCHAR(255) NULL,
 expires_at BIGINT NOT NULL,
 created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS qha_rate_limits (
 rate_key CHAR(64) CHARACTER SET ascii NOT NULL PRIMARY KEY,
 hits INT UNSIGNED NOT NULL,
 reset_at BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
